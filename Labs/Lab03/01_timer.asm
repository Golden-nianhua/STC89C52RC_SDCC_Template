; Lab03-01：利用定时器0生成实时时钟，在动态数码管上显示“时 分 秒”。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 时钟参数：12 MHz 晶振、6T 模式，定时器每 0.5 us 加 1。
; -----------------------------------------------------------------------------
        .module  lab03_01_timer      ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
LedOut0 =        0x71               ; 数码管第0位显示缓存（时高位）。
LedOut1 =        0x72               ; 数码管第1位显示缓存（时低位）。
LedOut2 =        0x73               ; 数码管第2位显示缓存（分隔符）。
LedOut3 =        0x74               ; 数码管第3位显示缓存（分高位）。
LedOut4 =        0x75               ; 数码管第4位显示缓存（分低位）。
LedOut5 =        0x76               ; 数码管第5位显示缓存（分隔符）。
LedOut6 =        0x77               ; 数码管第6位显示缓存（秒高位）。
LedOut7 =        0x78               ; 数码管第7位显示缓存（秒低位）。
MsValue  =       0x79               ; 25 ms 节拍计数器，累计 40 次为 1 秒。
SecValue =       0x7A               ; 秒计数器，范围0~59。
MinValue =       0x7B               ; 分计数器，范围0~59。
HourValue=       0x7C               ; 时计数器，范围0~23。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到主程序入口。
; -----------------------------------------------------------------------------
        .org      0x000B            ; 定时器0中断入口地址。
        push      acc               ; 保存累加器ACC现场。
        mov       tl0, #0xB0        ; 重新装载低 8 位；0x3CB0 至溢出共计 50000 次。
        mov       th0, #0x3C        ; 重新装载高 8 位；50000 * 0.5 us = 25 ms。
        inc       MsValue           ; 25 ms 节拍计数器加 1。
        mov       a, MsValue        ; 将节拍计数值送入 A。
        cjne      a, #40, tt0       ; 未满 40 次则退出；40 * 25 ms = 1 s。
        mov       MsValue, #0       ; 满 1 秒，节拍计数器清零。
        inc       SecValue          ; 秒计数器加1。
        mov       a, SecValue       ; 将秒计数值送入A。
        cjne      a, #60, tt0       ; 判断是否满60秒，未满则跳转到tt0退出。
        mov       SecValue, #0      ; 满60秒，秒计数器清零。
        inc       MinValue          ; 分计数器加1。
        mov       a, MinValue       ; 将分计数值送入A。
        cjne      a, #60, tt0       ; 判断是否满60分，未满则跳转到tt0退出。
        mov       MinValue, #0      ; 满60分，分计数器清零。
        inc       HourValue         ; 时计数器加1。
        mov       a, HourValue      ; 将时计数值送入A。
        cjne      a, #24, tt0       ; 判断是否满24小时，未满则跳转到tt0退出。
        mov       HourValue, #0     ; 满24小时，时计数器清零。
tt0:    pop       acc               ; 恢复累加器ACC现场。
        reti                        ; 中断返回。
; -----------------------------------------------------------------------------
main:                               ; 主程序入口，只在复位后执行一次初始化。
        mov       sp, #0x2F         ; 将栈底移到 0x30，避免压栈占用普通低地址 RAM。
        mov       MsValue, #0       ; 初始化 25 ms 节拍计数器为 0。
        mov       SecValue, #0      ; 初始化秒计数器为0。
        mov       MinValue, #0      ; 初始化分计数器为0。
        mov       HourValue, #0     ; 初始化时计数器为0。
        mov       tl0, #0xB0        ; 初始化定时器0低8位初值。
        mov       th0, #0x3C        ; 初始化定时器0高8位初值。
        mov       tmod, #0x01       ; 设置TMOD，定时器0工作在模式1（16位定时器）。
        setb      tr0               ; 启动定时器0。
        setb      ea                ; 开启总中断。
        setb      et0               ; 开启定时器0中断。
main1:                              ; 主循环入口。
        lcall     timedisp          ; 调用时间数据处理子程序，拆分时分秒。
        lcall     disp              ; 调用数码管动态显示子程序。
        ljmp      main1             ; 无限循环，持续刷新显示。
; -----------------------------------------------------------------------------
disp:                               ; 数码管动态扫描显示子程序。
        mov       dptr, #tab        ; DPTR指向段码表首地址。
        mov       r1, #0            ; R1作为位选计数器，初始为0（选中第0位）。
        mov       r7, #8            ; R7作为循环计数器，共8位数码管。
        mov       r0, #LedOut0      ; R0指向显示缓存区首地址（LedOut0）。
disp1:                              ; 动态显示循环入口。
        mov       a, @r0            ; 读取当前位的显示数据。
        inc       r0                ; R0指向下一个显示缓存单元。
        movc      a, @a+dptr        ; 查表获取对应的段码。
        mov       p0, a             ; 将段码送到P0口显示。
        mov       p2, r1            ; 将位选信号送到P2口。
        inc       r1                ; 位选计数器加1，准备下一位。
        lcall     delay             ; 调用短延时，保证亮度。
        mov       p0, #0x00         ; 消隐，防止数码管显示重影。
        djnz      r7, disp1         ; R7减1，若不为0则继续循环显示下一位。
        ret                         ; 8位显示完毕，返回主程序。
; -----------------------------------------------------------------------------
delay:                              ; 短延时子程序，用于数码管动态扫描。
        mov       r5, #0            ; 将R5设为0，DJNZ循环执行256次。
delay_:
        djnz      r5, delay_        ; R5 减 1，不为 0 则跳回 delay_ 标签。
        ret                         ; 延时结束返回。
; -----------------------------------------------------------------------------
timedisp:                           ; 时间数据处理子程序，将时分秒拆分为十进制个位和十位。
        mov       a, HourValue      ; 读取小时值。
        mov       b, #10            ; 除数设为10。
        div       ab                ; A/B，商在A（十位），余数在B（个位）。
        mov       LedOut0, a        ; 保存小时十位。
        mov       LedOut1, b        ; 保存小时个位。
        mov       a, MinValue       ; 读取分钟值。
        mov       b, #10            ; 除数设为10。
        div       ab                ; 拆分分钟。
        mov       LedOut3, a        ; 保存分钟十位。
        mov       LedOut4, b        ; 保存分钟个位。
        mov       a, SecValue       ; 读取秒值。
        mov       b, #10            ; 除数设为10。
        div       ab                ; 拆分秒。
        mov       LedOut6, a        ; 保存秒十位。
        mov       LedOut7, b        ; 保存秒个位。
        mov       LedOut2, #0x10    ; 设置分隔符（对应段码表索引0x10，即“-”或“.”）。
        mov       LedOut5, #0x10    ; 设置分隔符。
        ret                         ; 返回主程序。
; -----------------------------------------------------------------------------
tab:                                ; 共阳数码管段码表，位序为 DP-G-F-E-D-C-B-A。
        .db       0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F ; 0-9
        .db       0x77, 0x7C, 0x39, 0x5E, 0x79, 0x71, 0x00                     ; A-F, 熄灭
; -----------------------------------------------------------------------------
