; Lab01-06：使用连续采样计数消抖的 P1.3 按键控制 P1.4 上的继电器。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 时钟条件：12 MHz 晶振、6T 模式；每约 10 ms 采样一次。
; 原理：连续 5 次采样到相同电平（约 50 ms），才确认按键状态。
; -----------------------------------------------------------------------------
        .module  lab01_06_relay2    ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
K1      =         0x93              ; P1.3 的位地址，按键按下时输入低电平。
RELAY   =         0x94              ; P1.4 的位地址，用于输出继电器控制电平。
LAST_K1 =         0x00              ; 位地址 0x00：保存当前正在确认的候选电平。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，只在复位后执行一次初始化。
        mov       sp, #0x2F         ; 将栈底移到 0x30，避免压栈占用低地址寄存器区。
        setb      K1                ; 向 P1.3 写 1，将准双向口释放为按键输入状态。
        setb      RELAY             ; 上电时先按松开状态处理，避免继电器误吸合。
        mov       c, K1             ; 读取第一次按键电平，作为候选状态。
        mov       LAST_K1, c        ; 保存候选状态，后续采样与它比较。
        mov       r5, #0             ; 连续相同采样次数清零。
main_loop:                         ; 每约 10 ms 执行一次按键采样。
        acall     debounce_10ms     ; 等待约 10 ms，形成固定采样周期。
        mov       c, K1             ; 读取当前按键电平并暂存在进位标志 C 中。
        jb        LAST_K1, candidate_high ; 候选为高电平时转入高电平比较。
        jc        sample_changed    ; 候选低、当前高：候选变化，重新计数。
        sjmp      sample_same       ; 候选低、当前低：连续相同一次。
candidate_high:                    ; 当前候选状态为高电平。
        jnc       sample_changed    ; 候选高、当前低：候选变化，重新计数。
sample_same:                       ; 当前采样与候选状态相同。
        inc       r5                 ; 连续相同采样次数加一。
        cjne      r5, #5, main_loop ; 未达到 5 次时继续每 10 ms 采样。
        jb        LAST_K1, stable_high ; 连续 5 次为高，确认松开状态。
        clr       RELAY             ; 连续 5 次为低，确认按下，输出低电平。
        sjmp      stable_done       ; 清零计数并开始下一轮确认。
stable_high:                       ; 连续 5 次采样均为高电平。
        setb      RELAY             ; 确认松开，将 P1.4 输出高电平。
stable_done:                       ; 一次稳定状态确认完成。
        mov       r5, #0             ; 清零计数，避免计数器溢出后再次误触发。
        sjmp      main_loop         ; 继续以 10 ms 周期采样。
sample_changed:                    ; 采样与候选状态不同，可能仍在抖动。
        mov       LAST_K1, c        ; 将新电平作为新的候选状态。
        mov       r5, #0             ; 反向采样使连续稳定计数重新开始。
        sjmp      main_loop         ; 等待候选状态连续稳定约 50 ms。
; -----------------------------------------------------------------------------
debounce_10ms:                     ; 约 10 ms 软件延时，使用 R6 和 R7 组成双层循环。
        mov       r6, #41           ; 外层循环 40 次；12 MHz、6T 时每机器周期约 0.5 us。
debounce_outer:                    ; 外层循环入口，每轮重新装载内层循环计数器。
        mov       r7, #250         ; 内层循环 250 次，以 DJNZ 消耗主要延时时间。
debounce_inner:                    ; 内层延时循环入口。
        djnz      r7, debounce_inner ; R7 减 1，未减到 0 时继续内层循环。
        djnz      r6, debounce_outer ; R6 减 1，未减到 0 时开始下一轮内层循环。
        ret                         ; 延时结束，返回采样流程。
