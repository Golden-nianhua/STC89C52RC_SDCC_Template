; Lab01-05：使用 P1.3 按键控制连接在 P1.4 上的继电器。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 原理：K1 为高电平时使继电器控制端输出高电平，否则输出低电平。
; -----------------------------------------------------------------------------
        .module  lab01_05_relay     ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
K1      =         0x93              ; P1.3 的位地址；按键输入由原图中的 P2.7 改到 P1.3。
RELAY   =         0x94              ; P1.4 的位地址，用于输出继电器控制电平。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，只在复位后执行一次初始化。
        mov       sp, #0x2F         ; 将栈底移到 0x30，避免后续压栈占用低地址寄存器区。
        setb      K1                ; 向 P1.3 写 1，将准双向口释放为按键输入状态。
main_loop:                         ; 按键扫描循环入口，持续读取 K1 并更新继电器输出。
        jb        K1, key_high      ; K1 为 1 时跳转；为 0 时顺序执行低电平分支。
        clr       RELAY             ; K1 为低电平，将 P1.4 输出低电平。
        sjmp      main_loop         ; 返回循环入口，继续读取按键状态。
key_high:                          ; K1 为高电平时执行的分支入口。
        setb      RELAY             ; 将 P1.4 输出高电平。
        sjmp      main_loop         ; 返回循环入口，继续读取按键状态。
