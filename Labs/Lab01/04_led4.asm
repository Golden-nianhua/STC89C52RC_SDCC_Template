; Lab01-04：使用循环移位实现 P2 口流水灯，灯效与 Lab01-03 相同。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 优化思路：用累加器 A 保存灯态，每轮通过 RL A 把低电平位循环左移一位。
; -----------------------------------------------------------------------------
        .module  lab01_04_led4      ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
P2      =         0xA0              ; 定义 P2 特殊功能寄存器的直接地址为 0xA0。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，仅在复位后初始化一次流水灯状态。
        mov       a, #0xFE          ; 初始灯态为 11111110，使 P2.0 对应的 LED 点亮。
loop:                              ; 流水灯循环入口，每轮显示并移动一次低电平位。
        mov       P2, a             ; 将累加器 A 中的当前灯态输出到 P2 口。
        acall     delay             ; 调用同一 2 KB 页内的延时程序，保持当前灯态可见。
        rl        a                 ; A 循环左移一位，使唯一的 0 依次移向 P2.1 至 P2.7。
        sjmp      loop              ; 返回循环入口；第八次移位后 A 会自然恢复为 0xFE。
; -----------------------------------------------------------------------------
delay:                             ; 延时子程序入口，使用 R5、R6、R7 组成三层空循环。
        mov       r5, #0x04         ; 设置最外层循环次数为 4。
delay1:                            ; 最外层循环起点，每轮都会重新装载 R6。
        mov       r6, #0xFF         ; 设置中间层循环次数为 255。
delay2:                            ; 中间层循环起点，每轮都会重新装载 R7。
        mov       r7, #0xFF         ; 设置最内层循环次数为 255。
delay3:                            ; 最内层循环起点，用于消耗主要的延时时间。
        djnz      r7, delay3        ; R7 减 1；结果不为 0 时继续执行最内层循环。
        djnz      r6, delay2        ; R6 减 1；结果不为 0 时重装 R7 并继续中间层循环。
        djnz      r5, delay1        ; R5 减 1；结果不为 0 时重装 R6 并继续最外层循环。
        ret                         ; 延时结束，返回主循环中 ACALL 的下一条指令。
