; Lab02-03：改进 8 位数码管动态扫描，消除相邻数码管上的余辉。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 段选：P0.0 至 P0.7 经 74HC245 依次连接 A、B、C、D、E、F、G、DP。
; 位选：P2.2 至 P2.4 经 74HC138 译码后选择 8 位数码管中的一位。
; 余辉原因：先切换位选、后更新段码时，新选中的数码管会短暂显示上一位的段码。
; 改进方法：每次切换位选前先关闭全部段，再选择新位置并输出新段码。
; -----------------------------------------------------------------------------
        .module  lab02_03_nixie3    ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
SMG_PORT =        0x80              ; P0 特殊功能寄存器地址，用作数码管段选端口。
SMG_SELECT =      0xA0              ; P2 特殊功能寄存器地址，P2.2 至 P2.4 用作位选。
LED_OUT0 =        0x72              ; 内部 RAM 0x72：保存第 0 位数码管显示的数字。
LED_OUT1 =        0x73              ; 内部 RAM 0x73：保存第 1 位数码管显示的数字。
LED_OUT2 =        0x74              ; 内部 RAM 0x74：保存第 2 位数码管显示的数字。
LED_OUT3 =        0x75              ; 内部 RAM 0x75：保存第 3 位数码管显示的数字。
LED_OUT4 =        0x76              ; 内部 RAM 0x76：保存第 4 位数码管显示的数字。
LED_OUT5 =        0x77              ; 内部 RAM 0x77：保存第 5 位数码管显示的数字。
LED_OUT6 =        0x78              ; 内部 RAM 0x78：保存第 6 位数码管显示的数字。
LED_OUT7 =        0x79              ; 内部 RAM 0x79：保存第 7 位数码管显示的数字。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，只在复位后执行一次初始化。
        mov       sp, #0x2F         ; 将栈底移到 0x30，避免压栈占用显示缓冲区。
        mov       LED_OUT0, #0x00   ; 第 0 位显示数字 0。
        mov       LED_OUT1, #0x01   ; 第 1 位显示数字 1。
        mov       LED_OUT2, #0x02   ; 第 2 位显示数字 2。
        mov       LED_OUT3, #0x03   ; 第 3 位显示数字 3。
        mov       LED_OUT4, #0x04   ; 第 4 位显示数字 4。
        mov       LED_OUT5, #0x05   ; 第 5 位显示数字 5。
        mov       LED_OUT6, #0x06   ; 第 6 位显示数字 6。
        mov       LED_OUT7, #0x07   ; 第 7 位显示数字 7。
main_loop:                         ; 主循环不断刷新整组数码管。
        lcall     display           ; 调用一次扫描程序，依次刷新 8 个位置。
        sjmp      main_loop         ; 一轮结束后立即开始下一轮，保持画面稳定。
; -----------------------------------------------------------------------------
display:                           ; 带切换消隐的 8 位动态扫描子程序。
        mov       dptr, #segment_code ; DPTR 指向代码区中的数字段码表。
        mov       r1, #0x00         ; R1 保存当前位号，从第 0 位开始扫描。
        mov       r7, #0x08         ; R7 保存本轮剩余位数，一共扫描 8 位。
        mov       r0, #LED_OUT0     ; R0 指向第一个显示缓冲字节 0x72。
display_next:                      ; 单个数码管位置的扫描入口。
        mov       SMG_PORT, #0x00   ; 切换位置前关闭全部段，阻断上一位段码形成的余辉。
        mov       a, r1             ; 将当前位号送入累加器 A。
        inc       r1                ; 位号加 1，为下一个数码管位置做准备。
        rl        a                 ; 位号循环左移一位，相当于乘以 2。
        rl        a                 ; 再左移一位，相当于乘以 4，送到 P2.2 至 P2.4。
        mov       SMG_SELECT, a     ; 输出位选编码，经 74HC138 选择新的数码管位置。
        mov       a, @r0            ; 从内部 RAM 读取当前数码管要显示的数字。
        inc       r0                ; 显示缓冲区指针移到下一位。
        movc      a, @a+dptr        ; 以数字为索引，从代码区读取对应段码。
        mov       SMG_PORT, a       ; 位选稳定后输出新段码，点亮当前数码管。
        lcall     display_delay     ; 短暂保持当前位点亮，提供足够的可见亮度。
        djnz      r7, display_next  ; 剩余位数减 1；未扫描完 8 位时继续下一位。
        ret                         ; 8 位全部刷新完成，返回主循环。
; -----------------------------------------------------------------------------
display_delay:                     ; 单个位的短延时子程序。
        mov       r5, #200          ; 设置延时循环次数为 200。
display_delay_loop:                ; 短延时循环入口。
        djnz      r5, display_delay_loop ; R5 减 1，未到 0 时继续等待。
        ret                         ; 延时结束，返回动态扫描程序。
; -----------------------------------------------------------------------------
segment_code:                      ; 共阴数码管数字 0 至 9及熄灭状态的段码表。
        .db       0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07 ; 0 至 7。
        .db       0x7F, 0x6F, 0x00  ; 8、9以及全部段熄灭。
