; Lab02-06：矩阵按键。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 按键：P1.0 至 P1.7 连接 4x4 矩阵按键。
; 显示：P0.0 至 P0.7 依次连接 A、B、C、D、E、F、G、DP，共阳数码管。
; 原理：扫描到矩阵按键后延时约 10 ms 消抖，将按键编号写入 KEY_VALUE 并查表显示。
; -----------------------------------------------------------------------------
        .module  lab02_06_key2      ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
SMG_PORT =        0x80              ; P0 特殊功能寄存器地址，用作数码管段选端口。
KEY_PORT =        0x90              ; P1 特殊功能寄存器地址，用作 4x4 矩阵按键输入。
KEY_VALUE =       0x70              ; 内部 RAM 0x70：保存当前需要显示的按键编号。
KEY_STATE =       0x00              ; 位寻址区 00H：按键状态标志（0 表示无按键，1 表示有按键）。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，只在复位后执行一次初始化。
        mov       sp, #0x2F         ; 将栈底移到 0x30，避免压栈占用普通低地址 RAM。
        mov       dptr, #segment_code ; DPTR 指向共阳数码管 0 至 F 的段码表。
main_loop:                         ; 主循环持续扫描按键并更新显示。
        lcall     key_scan          ; 扫描矩阵按键；按下后更新 KEY_VALUE。
        jnb       KEY_STATE, main_loop ; 若按键状态标志为 0（无有效按键），则继续循环。
        mov       a, KEY_VALUE      ; 将需要显示的数字作为段码表索引。
        movc      a, @a+dptr        ; 从代码区读取对应的共阳数码管段码。
        mov       SMG_PORT, a       ; 把段码送到 P0，显示当前按键编号。
        ljmp      main_loop         ; 返回主循环，继续扫描按键。
; -----------------------------------------------------------------------------
key_scan:                          ; 4x4 矩阵按键的扫描子程序。
        clr       KEY_STATE         ; 清除按键状态标志，准备重新检测。
        lcall     s_key             ; 读取按键电平，判断是否有按键按下。
        jz        key00             ; 若读取结果为 0（无按键），直接跳转到 key00 退出。
        mov       r7, #10           ; 执行 10 次约 1 ms 延时，总计约 10 ms 消抖。
        lcall     delay_1ms         ; 等待触点抖动结束。
        lcall     s_key             ; 再次读取按键电平，确认按键确实按下。
        jnz       key1              ; 若读取结果非 0，说明有按键按下，进入矩阵识别。
key00:                             ; 无有效按键或消抖后按键已松开的公共出口。
        ret                         ; 返回主循环，保持原显示值。
; -----------------------------------------------------------------------------
; 矩阵按键识别逻辑：
; 先向 P1 写入 0x0F（高 4 位为 0，低 4 位为 1），读入低 4 位；
; 再向 P1 写入 0xF0（低 4 位为 0，高 4 位为 1），读入高 4 位；
; 将两次读取的值组合，得到特征码，依次比较以确定按键编号（0~15）。
; -----------------------------------------------------------------------------
key1:                              ; 判断是否为矩阵按键 0（首次扫描并计算特征码）。
        mov       KEY_PORT, #0x0F   ; 向 P1 写入 0x0F，使高 4 位输出 0，低 4 位为输入状态。
        nop                         ; 空操作，等待端口电平稳定。
        mov       a, KEY_PORT       ; 读取 P1 端口当前电平。
        anl       a, #0x0F          ; 屏蔽高 4 位，仅保留低 4 位的列状态。
        mov       b, a              ; 将低 4 位暂存到 B 寄存器。
        mov       KEY_PORT, #0xF0   ; 向 P1 写入 0xF0，使低 4 位输出 0，高 4 位为输入状态。
        nop                         ; 空操作，等待端口电平稳定。
        mov       a, KEY_PORT       ; 再次读取 P1 端口当前电平。
        anl       a, #0xF0          ; 屏蔽低 4 位，仅保留高 4 位的行状态。
        orl       a, b              ; 将高 4 位与暂存的低 4 位组合，形成按键特征码（保存在 A 中）。
        cjne      a, #0xEE, key2    ; 比较特征码是否为 0xEE（第 0 行第 0 列），不是则跳转 key2。
        mov       KEY_VALUE, #0     ; 若是，记录按键编号为 0。
        ljmp      key0              ; 跳转到 key0，等待按键释放。
; -----------------------------------------------------------------------------
; 以下利用 CJNE 不改变 A 值的特性，直接连续比对特征码
; -----------------------------------------------------------------------------
key2:                              ; 判断是否为矩阵按键 1。
        cjne      a, #0xDE, key3    ; 比较 A 中特征码是否为 0xDE（第 1 行第 0 列），不是则跳转 key3。
        mov       KEY_VALUE, #1     ; 若是，记录按键编号为 1。
        ljmp      key0              ; 跳转到 key0，等待按键释放。
; -----------------------------------------------------------------------------
key3:                              ; 判断是否为矩阵按键 2。
        cjne      a, #0xBE, key4    ; 比较特征码是否为 0xBE（第 2 行第 0 列），不是则跳转 key4。
        mov       KEY_VALUE, #2     ; 若是，记录按键编号为 2。
        ljmp      key0
; -----------------------------------------------------------------------------
key4:                              ; 判断是否为矩阵按键 3。
        cjne      a, #0x7E, key5    ; 比较特征码是否为 0x7E（第 3 行第 0 列），不是则跳转 key5。
        mov       KEY_VALUE, #3     ; 若是，记录按键编号为 3。
        ljmp      key0
; -----------------------------------------------------------------------------
key5:                              ; 判断是否为矩阵按键 4。
        cjne      a, #0xED, key6    ; 比较特征码是否为 0xED（第 0 行第 1 列），不是则跳转 key6。
        mov       KEY_VALUE, #4     ; 若是，记录按键编号为 4。
        ljmp      key0
; -----------------------------------------------------------------------------
key6:                              ; 判断是否为矩阵按键 5。
        cjne      a, #0xDD, key7    ; 比较特征码是否为 0xDD（第 1 行第 1 列），不是则跳转 key7。
        mov       KEY_VALUE, #5     ; 若是，记录按键编号为 5。
        ljmp      key0
; -----------------------------------------------------------------------------
key7:                              ; 判断是否为矩阵按键 6。
        cjne      a, #0xBD, key8    ; 比较特征码是否为 0xBD（第 2 行第 1 列），不是则跳转 key8。
        mov       KEY_VALUE, #6     ; 若是，记录按键编号为 6。
        ljmp      key0
; -----------------------------------------------------------------------------
key8:                              ; 判断是否为矩阵按键 7。
        cjne      a, #0x7D, key9    ; 比较特征码是否为 0x7D（第 3 行第 1 列），不是则跳转 key9。
        mov       KEY_VALUE, #7     ; 若是，记录按键编号为 7。
        ljmp      key0
; -----------------------------------------------------------------------------
key9:                              ; 判断是否为矩阵按键 8。
        cjne      a, #0xEB, keya    ; 比较特征码是否为 0xEB（第 0 行第 2 列），不是则跳转 keya。
        mov       KEY_VALUE, #8     ; 若是，记录按键编号为 8。
        ljmp      key0
; -----------------------------------------------------------------------------
keya:                              ; 判断是否为矩阵按键 9。
        cjne      a, #0xDB, keyb    ; 比较特征码是否为 0xDB（第 1 行第 2 列），不是则跳转 keyb。
        mov       KEY_VALUE, #9     ; 若是，记录按键编号为 9。
        ljmp      key0
; -----------------------------------------------------------------------------
keyb:                              ; 判断是否为矩阵按键 10 (A)。
        cjne      a, #0xBB, keyc    ; 比较特征码是否为 0xBB（第 2 行第 2 列），不是则跳转 keyc。
        mov       KEY_VALUE, #10    ; 若是，记录按键编号为 10 (对应十六进制 A)。
        ljmp      key0
; -----------------------------------------------------------------------------
keyc:                              ; 判断是否为矩阵按键 11 (B)。
        cjne      a, #0x7B, keyd    ; 比较特征码是否为 0x7B（第 3 行第 2 列），不是则跳转 keyd。
        mov       KEY_VALUE, #11    ; 若是，记录按键编号为 11 (对应十六进制 B)。
        ljmp      key0
; -----------------------------------------------------------------------------
keyd:                              ; 判断是否为矩阵按键 12 (C)。
        cjne      a, #0xE7, keye    ; 比较特征码是否为 0xE7（第 0 行第 3 列），不是则跳转 keye。
        mov       KEY_VALUE, #12    ; 若是，记录按键编号为 12 (对应十六进制 C)。
        ljmp      key0
; -----------------------------------------------------------------------------
keye:                              ; 判断是否为矩阵按键 13 (D)。
        cjne      a, #0xD7, keyf    ; 比较特征码是否为 0xD7（第 1 行第 3 列），不是则跳转 keyf。
        mov       KEY_VALUE, #13    ; 若是，记录按键编号为 13 (对应十六进制 D)。
        ljmp      key0
; -----------------------------------------------------------------------------
keyf:                              ; 判断是否为矩阵按键 14 (E)。
        cjne      a, #0xB7, keyg    ; 比较特征码是否为 0xB7（第 2 行第 3 列），不是则跳转 keyg。
        mov       KEY_VALUE, #14    ; 若是，记录按键编号为 14 (对应十六进制 E)。
        ljmp      key0
; -----------------------------------------------------------------------------
keyg:                              ; 判断是否为矩阵按键 15 (F)。
        cjne      a, #0x77, keyh    ; 比较特征码是否为 0x77（第 3 行第 3 列），不是则跳转 keyh。
        mov       KEY_VALUE, #15    ; 若是，记录按键编号为 15 (对应十六进制 F)。
        ljmp      key0
; -----------------------------------------------------------------------------
key0:                              ; 等待按键释放处理。
        mov       r7, #10           ; 执行 10 次约 1 ms 延时，总计约 10 ms。
        lcall     delay_1ms         ; 延时消抖。
        lcall     s_key             ; 再次读取按键电平，判断按键是否已释放。
        jnz       key0              ; 若非 0（按键未释放），则循环等待。
        setb      KEY_STATE         ; 按键已释放，置位按键状态标志，通知主程序更新显示。
keyh:                              ; 无效按键（如噪声）的公共出口。
        ret                         ; 返回主循环。
; -----------------------------------------------------------------------------
s_key:                             ; 读取矩阵按键是否有按下的子程序。
        mov       KEY_PORT, #0x0F   ; 向 P1 写入 0x0F，使高 4 位输出 0，低 4 位为输入。
        nop                         ; 空操作，等待端口电平稳定。
        mov       a, KEY_PORT       ; 读取 P1 端口电平。
        cpl       a                 ; 逐位取反，使低电平有效的按键状态变为高电平有效。
        anl       a, #0x0F          ; 屏蔽高 4 位，仅保留低 4 位的按键状态。
        ret                         ; 返回，A 中非 0 表示有按键按下。
; -----------------------------------------------------------------------------
delay_1ms:                         ; 约 1 ms 延时；R7 由调用者设置为重复次数。
        mov       r6, #249          ; 内层循环执行 249 次。
delay_1ms_loop:                    ; 1 ms 延时的内层循环入口。
        nop                         ; 空操作，用于延时。
        nop                         ; 空操作，用于延时。
        djnz      r6, delay_1ms_loop ; R6 减 1，未到 0 时继续内层循环。
        djnz      r7, delay_1ms     ; R7 减 1，未到 0 时再次执行约 1 ms 延时。
        ret                         ; 所有延时轮次完成，返回按键扫描程序。
; -----------------------------------------------------------------------------
segment_code:                      ; 共阳数码管 0 至 F 的段码表，位序为 DP-G-F-E-D-C-B-A。
        .db       0xC0, 0xF9, 0xA4, 0xB0, 0x99, 0x92, 0x82, 0xF8 ; 0 至 7。
        .db       0x80, 0x90, 0x88, 0x83, 0xC6, 0xA1, 0x86, 0x8E ; 8、9、A 至 F。
; -----------------------------------------------------------------------------