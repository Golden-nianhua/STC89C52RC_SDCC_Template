; Lab02-01：使用 P0 口驱动一位共阳数码管显示数字 0。
; 汇编器：SDCC 工具链中的 SDAS8051。
; 接线：P0.0 至 P0.7 依次连接 A、B、C、D、E、F、G、DP 段。
; 原理：查表取得共阴字模 0x3F，再逐位取反得到共阳字模 0xC0。
; -----------------------------------------------------------------------------
        .module  lab02_01_nixie     ; 声明当前汇编模块名称，供汇编器和链接器识别。
; -----------------------------------------------------------------------------
SMG_PORT =        0x80              ; P0 特殊功能寄存器地址，用作数码管段选端口。
; -----------------------------------------------------------------------------
        .area     PSEG (PAG,XDATA)  ; 声明分页外部 RAM 段；本实验不在该段分配数据。
        .area     XSEG (XDATA)      ; 声明外部 RAM 段，满足 SDCC MCS-51 链接布局要求。
; -----------------------------------------------------------------------------
        .area     HOME (ABS, CODE)  ; 声明绝对地址代码段，用于放置复位入口和程序代码。
        .org      0x0000            ; 将下一条指令放在单片机复位向量地址 0x0000。
        ljmp      main              ; 复位后长跳转到位于 0x0030 的主程序入口。
; -----------------------------------------------------------------------------
        .org      0x0030            ; 主程序从 0x0030 开始，避开前面的中断向量区域。
main:                              ; 主程序入口，只在复位后执行一次初始化。
        mov       sp,   #0x2F       ; 将栈底移到 0x30，避免后续压栈占用低地址寄存器区。
        mov       dptr, #segment_code ; DPTR 指向代码区中的 0 至 F 段码表。
        mov       a, #0x00          ; A 作为表索引；索引 0 选择数字 0 的段码。
        movc      a, @a+dptr        ; 从代码区读取第 0 项共阴字模 0x3F。
        cpl       a                 ; 全部位取反，转换为共阳数码管所需的 0xC0。
        mov       SMG_PORT, a       ; 将段码送到 P0，点亮 A 至 F 段并关闭 G、DP。
hold:                              ; 显示保持循环入口。
        sjmp      hold              ; 不断跳回自身，使数字 0 持续显示。
; -----------------------------------------------------------------------------
segment_code:                      ; 共阴数码管 0 至 F 的段码表，位序为 DP-G-F-E-D-C-B-A。
        .db       0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07 ; 0 至 7。
        .db       0x7F, 0x6F, 0x77, 0x7C, 0x39, 0x5E, 0x79, 0x71 ; 8、9、A 至 F。
